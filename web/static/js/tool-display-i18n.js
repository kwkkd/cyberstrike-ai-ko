    function isKoreanUi() {
        try {
            if (typeof window.uiLocale === 'function') return window.uiLocale() === 'ko-KR';
            if (window.currentLanguage) return window.currentLanguage === 'ko-KR';
            if (window.i18n && typeof window.i18n.language === 'string') return window.i18n.language === 'ko-KR';
        } catch (e) { /* ignore */ }
        return false;
    }

